        document.addEventListener('DOMContentLoaded', function() {
            var rewardBtn = document.getElementById('rewardBtn');
            var rewardPopup = document.getElementById('rewardPopup');

            if (rewardBtn && rewardPopup) {
                rewardBtn.addEventListener('mouseenter', function() {
                    rewardPopup.style.display = 'block';
                });

                rewardBtn.addEventListener('mouseleave', function() {
                    rewardPopup.style.display = 'none';
                });
            }

            var themeToggle = document.getElementById('themeToggle');
            if (themeToggle) {
                var themeIcon = themeToggle.querySelector('i');

                function setTheme(theme) {
                    if (theme === 'light') {
                        document.documentElement.setAttribute('data-theme', 'light');
                        themeIcon.className = 'fas fa-moon';
                        localStorage.setItem('theme', 'light');
                    } else {
                        document.documentElement.removeAttribute('data-theme');
                        themeIcon.className = 'fas fa-sun';
                        localStorage.setItem('theme', 'dark');
                    }
                }

                var savedTheme = localStorage.getItem('theme');
                if (savedTheme) {
                    setTheme(savedTheme);
                } else if (window.matchMedia && window.matchMedia('(prefers-color-scheme: light)').matches) {
                    setTheme('light');
                } else {
                    setTheme('dark');
                }

                themeToggle.addEventListener('click', function() {
                    var currentTheme = document.documentElement.getAttribute('data-theme');
                    if (currentTheme === 'light') {
                        setTheme('dark');
                    } else {
                        setTheme('light');
                    }
                });
            }

            var backToTopButton = document.getElementById('backToTop');

            if (backToTopButton) {
                backToTopButton.style.display = 'none';

                window.addEventListener('scroll', function() {
                    if (window.pageYOffset > 300) {
                        backToTopButton.style.display = 'flex';
                    } else {
                        backToTopButton.style.display = 'none';
                    }
                });

                backToTopButton.addEventListener('click', function() {
                    window.scrollTo({
                        top: 0,
                        behavior: 'smooth'
                    });
                });
            }
        });
    </script>
